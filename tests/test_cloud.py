"""Offline adapter contract only; fake API is NOT a LEAN/cloud validation."""
import ast
import importlib.util
import json
from pathlib import Path
import sys
import types
import unittest
from datetime import datetime
ROOT=Path(__file__).resolve().parents[1]
class CloudContract(unittest.TestCase):
    def test_bundle_matches_sources(self):
        config=json.loads((ROOT/'config/g0.json').read_text())
        expected='# Generated by tools/build_cloud.py; edit sources, then rebuild.\n'+(ROOT/'src/quant_g0/core.py').read_text()+'\nCONFIG = '+repr(config)+'\n'+(ROOT/'quantconnect/adapter.py').read_text()
        self.assertEqual((ROOT/'quantconnect/main.py').read_text(),expected)
    def test_no_order_network_or_performance_methods(self):
        tree=ast.parse((ROOT/'quantconnect/main.py').read_text())
        forbidden={'market_order','set_holdings','order','limit_order','market_on_open_order','download','plot','record','history','liquidate'}
        for n in ast.walk(tree):
            if isinstance(n,ast.Call) and isinstance(n.func,ast.Attribute):self.assertNotIn(n.func.attr,forbidden)
    def test_mock_stream_holdout_does_not_change_books(self):
        fake=types.ModuleType('AlgorithmImports');fake.QCAlgorithm=object
        old=sys.modules.get('AlgorithmImports');sys.modules['AlgorithmImports']=fake
        try:
            spec=importlib.util.spec_from_file_location('g0_cloud_contract',ROOT/'quantconnect/main.py');module=importlib.util.module_from_spec(spec);sys.modules[spec.name]=module;spec.loader.exec_module(module)
            a=module.G0Audit();a.assets={'SPY':'spy'};a.quality={'SPY':module.Quality([datetime(2010,1,4).date(),datetime(2010,1,5).date(),datetime(2023,1,3).date()])};a.actions={'SPY':dict(dividends=0,splits=0,invalid=0)}
            a.books=[module.Ledger(),module.Ledger(fee=1)];a.accounting_block=None;a.div_sample_count=0;a.dev_dividends=[];a.max_error=module.D(0);a.reconciled_days=0;a.last_dev=None;logs=[];a.debug=logs.append
            for day in [datetime(2010,1,4),datetime(2010,1,5),datetime(2023,1,3)]:
                b=types.SimpleNamespace(time=day,open=100,high=101,low=99,close=100,volume=10)
                a.on_data(types.SimpleNamespace(dividends={},splits={},bars={'spy':b}))
            self.assertEqual(a.reconciled_days,2);self.assertEqual(a.books[0].qty,100);self.assertEqual(a.quality['SPY'].count,3)
            self.assertFalse(any('2023' in line for line in logs))
        finally:
            if old is None:sys.modules.pop('AlgorithmImports',None)
            else:sys.modules['AlgorithmImports']=old
